import assert from 'node:assert/strict'
import { readFileSync, statSync } from 'node:fs'
import { collectAiFallbackReferences } from './aiFallbackReferenceInventory'

const inventory = collectAiFallbackReferences()
for (const path of inventory.paths) {
  assert.ok(path.startsWith('/assets/') && !path.includes('..') && !path.includes('\\'))
  assert.ok(statSync(`public${path}`).isFile(), `Missing fallback candidate: ${path}`)
}
const manifestPath = 'server/aiReferenceAssets.generated.ts'
const manifest = '// Generated by scripts/generateAiReferenceManifest.ts. Do not edit manually.\n'
  + '// Exact literal file URLs keep Vercel filesystem tracing bounded.\n'
  + "import { readFile } from 'node:fs/promises'\n\n"
  + 'export const aiReferenceAssetReaders: Record<string, () => Promise<Buffer>> = {\n'
  + inventory.paths.map(path => `  ${JSON.stringify(path)}: () => readFile(new URL(${JSON.stringify(`../public${path.split('/').map(segment => encodeURIComponent(segment)).join('/')}`)}, import.meta.url)),`).join('\n')
  + '\n}\n'
const config = JSON.parse(readFileSync('vercel.json', 'utf8'))
config.functions['api/generate-door-visualization.ts'].includeFiles = inventory.paths.map(path => `public${path}`)
const outputs = new Map([[manifestPath, manifest], ['vercel.json', `${JSON.stringify(config, null, 2)}\n`]])
if (process.argv.includes('--patch')) {
  // Emit an apply_patch input so generated files use the same reviewed editing
  // mechanism as hand-written code. Never write runtime files from this script.
  console.log('*** Begin Patch')
  for (const [file, content] of outputs) {
    const before = readFileSync(file, 'utf8')
    if (before === content) continue
    console.log(`*** Update File: ${file}\n@@\n${before.trimEnd().split('\n').map(line => `-${line}`).join('\n')}\n${content.trimEnd().split('\n').map(line => `+${line}`).join('\n')}`)
  }
  console.log('*** End Patch')
} else {
  for (const [file, content] of outputs) assert.equal(readFileSync(file, 'utf8'), content, `Stale ${file}; regenerate with --patch`)
  console.log(JSON.stringify({ assets: inventory.paths.length, assetBytes: inventory.paths.reduce((sum, path) => sum + statSync(`public${path}`).size, 0), referenceGroups: inventory.references.length, resolverCases: inventory.resolutions, sideliteFamilies: inventory.sideliteFamilies }))
}
